from modules.map_backgrounds import MAP_BACKGROUNDS
from modules.plotting_scripts import SiteLines
from modules.shape_viewer import locations_with_shape, shape_distances


def overview_map(map_style: str) -> dict:
    """
    Create overview map for the Home page.

    :param map_style: User selected map style

    :return:
        st_folium() map object
    """
    map_style = MAP_BACKGROUNDS[map_style]
    glacier_sites = gpd.GeoDataFrame(
        locations_with_shape(), geometry="geometry", crs="EPSG:4326"
    )

    map = folium.Map(
        tiles=map_style["tiles"],
        attr=map_style["attribution"],
    )
    minx, miny, maxx, maxy = glacier_sites.total_bounds.tolist()
    map.fit_bounds([[miny, minx], [maxy, maxx]])

    # Color each marker based on data availability in the database
    # Grey: None
    # Blue: Either shapes or statistics
    marker_js = """
    function(feature, latlng) {
        var color = (feature.properties.has_shapes || feature.properties.has_statistics) ? 'blue' : 'gray';
        return L.marker(latlng, {
            icon: L.AwesomeMarkers.icon({
                icon: 'star',
                markerColor: color,
                prefix: 'fa',
                iconColor: 'white'
            })
        });
    }
    """

    folium.GeoJson(
        glacier_sites,
        tooltip=folium.GeoJsonTooltip(
            fields=["Official_name"],
            aliases=["Name"],
            localize=True,
            sticky=False,
            labels=True,
            style="""
                background-color: #F0EFEF;
                border: 2px solid black;
                border-radius: 3px;
                box-shadow: 3px;
            """,
        ),
        point_to_layer=folium.utilities.JsCode(marker_js),
        marker=folium.Marker(icon=folium.Icon(icon="star")),
    ).add_to(map)

    return st_folium(
        map,
        use_container_width=True,
        returned_objects=["last_active_drawing"],
    )


def last_viewed_site(map_click: dict) -> dict | None:
    """
    Extract site properties from the last clicked map feature.

    :param map_click: Map interaction data from st_folium

    :return:
        Dictionary with site properties or None if no feature was clicked
    """
    map_click = map_click.get("last_active_drawing", {})
    if map_click:
        return map_click.get("properties", {})
    else:
        return None


def shape_color(map_element: dict, color_map: dict) -> dict:
    """
    Select a unique color for each iceberg from the color map.

    :param map_element: Map element to render
    :param color_map: Unique colors of all icebergs generated by :py:func:`unique_colors`

    :return:
        Dictionary with style settings for the map element
    """
    iceberg_id = map_element["properties"]["IcebergID"]

    line_color = "black"
    # Show the date combinations with different styles.
    # The early date has 0 as date_rank
    if map_element["properties"]["date_rank"] == 0:
        opacity = 0.7
        weight = 2
    else:
        opacity = 0.9
        weight = 4

    return {
        "color": line_color,
        "fillColor": color_map.get(iceberg_id, "#808080"),
        "weight": weight,
        "fillOpacity": opacity,
    }


def unique_colors(iceberg_sites: gpd.GeoDataFrame) -> dict:
    """
    Create a unique color for each iceberg.

    :param iceberg_sites: GeoDataFrame with icebergs

    :return:
        Dictionary with unique colors for each iceberg
    """
    iceberg_ids = sorted(iceberg_sites["IcebergID"].unique())
    palette = cc.glasbey[: len(iceberg_ids)]
    return {ice_id: palette[index] for index, ice_id in enumerate(iceberg_ids)}


def iceberg_map(
    iceberg_sites: gpd.GeoDataFrame,
) -> tuple[folium.FeatureGroup, gpd.GeoDataFrame]:
    """
    Create map feature group with iceberg shapes to add to the map.

    :param iceberg_sites: GeoDataFrame with icebergs to show in the map

    :return:
        Folium map object, Updated iceberg sites DataFrame
    """
    feature_group = folium.FeatureGroup(name="Iceberg Shapes")

    site_lines = shape_distances(iceberg_sites)
    iceberg_sites.to_crs("EPSG:4326", inplace=True)

    tooltip_opts = dict(
        localize=True,
        sticky=False,
        labels=True,
        style="""
        background-color: #F0EFEF;
        border: 2px solid black;
        border-radius: 3px;
        box-shadow: 3px;
    """,
    )

    # Shapes
    render_columns = ["IcebergID", "observed_date", "geom", "date_rank"]
    shape_colors = unique_colors(iceberg_sites)

    folium.GeoJson(
        iceberg_sites[render_columns],
        style_function=lambda x: shape_color(x, shape_colors),
        tooltip=folium.GeoJsonTooltip(
            fields=["observed_date", "IcebergID"],
            aliases=["Date", "Iceberg ID"],
            **tooltip_opts,
        ),
    ).add_to(feature_group)

    # Connecting lines
    folium.GeoJson(
        site_lines,
        style_function=lambda x: {
            "stroke": True,
            "color": shape_colors.get(x["properties"]["IcebergID"], "#808080"),
            "weight": 2,
            "opacity": 1.0,
        },
    ).add_to(feature_group)

    # Solid dot at the early end and hollow dot at the late end of each line
    early_points = gpd.GeoDataFrame(
        site_lines[["IcebergID"]],
        geometry=[Point(line.coords[0]) for line in site_lines.geometry],
        crs="EPSG:4326",
    )
    folium.GeoJson(
        early_points,
        style_function=lambda x: {
            "fillColor": shape_colors[x["properties"]["IcebergID"]]
        },
        marker=folium.CircleMarker(
            radius=4,
            color="#000000",
            weight=2,
            opacity=0.0,
            fill=True,
            fill_opacity=0.0,
        ),
    ).add_to(feature_group)

    late_points = gpd.GeoDataFrame(
        site_lines[["IcebergID"]],
        geometry=[Point(line.coords[-1]) for line in site_lines.geometry],
        crs="EPSG:4326",
    )
    folium.GeoJson(
        late_points,
        marker=folium.CircleMarker(
            radius=4,
            color="#000000",
            weight=2,
            opacity=0.0,
            fill=True,
            fill_color="#ffffff",
            fill_opacity=0.0,
        ),
    ).add_to(feature_group)

    # Add the tooltip as a invisible line with more area for a hover over
    folium.GeoJson(
        site_lines,
        style_function=lambda x: {"stroke": True, "weight": 20, "opacity": 0.0},
        highlight_function=lambda x: {"color": "#000000", "weight": 6, "opacity": 1.0},
        tooltip=folium.GeoJsonTooltip(
            fields=["distance_meters", "days_elapsed", "velocity_m_per_day"],
            aliases=["Distance (m):", "Time Elapsed (days):", "Velocity (m/day):"],
            **tooltip_opts,
        ),
    ).add_to(feature_group)

    SiteLines().add_to(feature_group)

    return feature_group, iceberg_sites
